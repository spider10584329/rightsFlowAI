USER_AUTOMATIONS = tuple(k for k, d in DEFINITIONS.items() if not d.system)
SYSTEM_AUTOMATIONS = tuple(k for k, d in DEFINITIONS.items() if d.system)
ERROR_HANDLER = "error_handler"


def get_definition(key: str) -> AutomationDefinition:
    definition = DEFINITIONS.get(key)
    if definition is None or definition.system:
        raise ValidationFailedError("Unknown automation", code="unknown_automation",
                                    details={"allowed": list(USER_AUTOMATIONS)})
    return definition


def automation_for_workflow(workflow: str | None) -> str | None:
    for definition in DEFINITIONS.values():
        if definition.workflow == workflow:
            return definition.key
    return None


def default_settings(key: str) -> dict[str, Any]:
    return DEFINITIONS[key].settings_model().model_dump()


def validate_settings(key: str, values: dict[str, Any] | None, *, base: dict[str, Any] | None = None) -> dict[str, Any]:
    """Merge ``values`` over ``base`` (or the defaults) and validate the result."""
    merged = {**(base if base is not None else default_settings(key)), **(values or {})}
    try:
        return DEFINITIONS[key].settings_model.model_validate(merged).model_dump()
    except ValidationError as exc:
        # Same shape as request validation errors, so clients map them to fields.
        raise ValidationFailedError(
            "Invalid automation settings", code="invalid_automation_settings",
            details=[{"loc": ["body", "settings", *[str(p) for p in e["loc"]]], "message": e["msg"],
                      "type": e["type"]} for e in exc.errors()],
        ) from exc


def stored_settings(key: str, values: dict[str, Any] | None) -> dict[str, Any]:
    """Settings as used: stored values over the current defaults; values that no
    longer validate (e.g. after a schema change) fall back to the defaults."""
    try:
        return validate_settings(key, values or {})
    except ValidationFailedError:
        return default_settings(key)


def required_scopes(automations: set[str]) -> list[str]:
    scopes: set[str] = set()
    for key in automations:
        scopes.update(DEFINITIONS[key].scopes)
    return sorted(scopes)


# --------------------------------------------------------------------------- schedules


def _offset(organization_id: str, key: str) -> int:
    return int(hashlib.sha256(f"{organization_id}:{key}".encode()).hexdigest()[:8], 16)


def _every(minutes: int, offset: int) -> str:
    if minutes < 60:
        start = offset % minutes
        return f"{','.join(str(start + step) for step in range(0, 60, minutes))} * * * *"
    hours = minutes // 60
    return f"{offset % 60} {'*' if hours == 1 else f'*/{hours}'} * * *"


def schedule(key: str, settings: dict[str, Any], organization_id: str) -> tuple[str | None, str]:
    """(cron expression in UTC, description). The error handler has no schedule."""
    offset = _offset(organization_id, key)
    minute = offset % 60
    if key in ("royalty_import", "ai_metadata_review"):
        minutes = settings["interval_minutes"]
        label = f"Every {minutes} minutes" if minutes < 60 else (
            "Every hour" if minutes == 60 else f"Every {minutes // 60} hours")
        return _every(minutes, offset), label
    if key == "contract_expiration":
        return f"{minute} {settings['hour_utc']} * * *", f"Daily at {settings['hour_utc']:02d}:{minute:02d} UTC"
    if key == "monthly_reporting":
        return (f"{minute} {settings['hour_utc']} {settings['day_of_month']} * *",
                f"Monthly on day {settings['day_of_month']} at {settings['hour_utc']:02d}:{minute:02d} UTC")
    if key == "automation_health":
        return f"{minute} * * * *", "Every hour"
    return None, "When a workflow fails"


def _field_matches(spec: str, value: int) -> bool:
    if spec == "*":
        return True
    for part in spec.split(","):
        if part.startswith("*/"):
            if value % int(part[2:]) == 0:
                return True
        elif int(part) == value:
            return True
    return False


def next_run(cron: str | None, after: datetime) -> datetime | None:
    """Next time (UTC, naive) the cron expressions built above fire. Supports
    only the forms ``schedule`` produces (numbers, lists, ``*`` and ``*/n``)."""
    if not cron:
        return None
    minute, hour, day, month, _weekday = cron.split()
    candidate = after.replace(second=0, microsecond=0) + timedelta(minutes=1)
    # At most one month ahead for the monthly schedule; check minute by minute
    # only inside matching hours to keep this cheap.
    limit = candidate + timedelta(days=62)
    while candidate <= limit:
        if not (_field_matches(month, candidate.month) and _field_matches(day, candidate.day)):
            candidate = (candidate + timedelta(days=1)).replace(hour=0, minute=0)
            continue
        if not _field_matches(hour, candidate.hour):
            candidate = (candidate + timedelta(hours=1)).replace(minute=0)
            continue
        if _field_matches(minute, candidate.minute):
            return candidate
        candidate += timedelta(minutes=1)
    return None


# --------------------------------------------------------------------------- templates


@lru_cache
def load_template(key: str) -> dict[str, Any]:
    return json.loads((TEMPLATE_DIR / f"{key}.json").read_text(encoding="utf-8"))


def template_version(key: str) -> int:
    return int(load_template(key)["meta"]["rightsflow"]["template_version"])


def render_template(key: str, values: dict[str, str]) -> dict[str, Any]:
    """The workflow body to send to n8n's public API: the template with every
    ``__RF_*__`` placeholder replaced and the build metadata removed."""
    template = load_template(key)

    def fill(node: Any) -> Any:
        if isinstance(node, str):
            for placeholder, value in values.items():
                if placeholder in node:
                    node = node.replace(placeholder, value)
            return node
        if isinstance(node, list):
            return [fill(item) for item in node]
        if isinstance(node, dict):
            return {k: fill(v) for k, v in node.items()}
        return node

    body = fill({k: v for k, v in template.items() if k != "meta"})
    leftover = sorted(set(_PLACEHOLDER_RE.findall(json.dumps(body))))
    if leftover:
        raise RuntimeError(f"Template {key} has unfilled placeholders: {', '.join(leftover)}")
    return body
