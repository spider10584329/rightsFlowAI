"""The automations an organization can switch on in managed mode.

Each definition names the n8n template it is provisioned from (generated by
automation/n8n/build_workflows.py into ``n8n_templates/``), the automation-key
scopes its workflow needs, and the settings people may change. Two system
workflows (health check and error handler) are provisioned alongside any
enabled automation and are not shown as switchable items.

Schedules are cron expressions in UTC. Each organization gets a stable minute
offset derived from its id, so organizations do not all start at :00.
"""

import hashlib
import json
import re
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from functools import lru_cache
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator

from app.core.errors import ValidationFailedError
from app.services.reports import REPORT_TYPES

TEMPLATE_DIR = Path(__file__).resolve().parent / "n8n_templates"
_PLACEHOLDER_RE = re.compile(r"__RF_[A-Z_]+__")


class _Settings(BaseModel):
    model_config = ConfigDict(extra="forbid")


class RoyaltyImportSettings(_Settings):
    # Start processing right after someone uploads a statement, instead of
    # waiting for the next scheduled run.
    process_on_upload: bool = True
    interval_minutes: Literal[15, 30, 60, 120] = 15


class ContractExpirationSettings(_Settings):
    thresholds: list[int] = Field(default_factory=lambda: [30, 14, 7], min_length=1, max_length=5)
    hour_utc: int = Field(default=7, ge=0, le=23)

    @field_validator("thresholds")
    @classmethod
    def _thresholds(cls, value: list[int]) -> list[int]:
        if any(not 1 <= day <= 365 for day in value):
            raise ValueError("Reminder thresholds must be between 1 and 365 days")
        return sorted(set(value), reverse=True)


class AIReviewSettings(_Settings):
    interval_minutes: Literal[30, 60, 120, 360] = 30


class MonthlyReportingSettings(_Settings):
    report_type: str = "revenue_by_source"
    day_of_month: int = Field(default=2, ge=1, le=28)
    hour_utc: int = Field(default=6, ge=0, le=23)

    @field_validator("report_type")
    @classmethod
    def _report_type(cls, value: str) -> str:
        if value not in REPORT_TYPES:
            raise ValueError(f"Unknown report type; choose one of {', '.join(REPORT_TYPES)}")
        return value


class NoSettings(_Settings):
    pass


@dataclass(frozen=True)
class AutomationDefinition:
    key: str
    # The workflow name n8n reports in runs ("royalty-import", ...).
    workflow: str
    label: str
    description: str
    scopes: tuple[str, ...]
    settings_model: type[_Settings] = NoSettings
    system: bool = False
    # Outbox events that make the backend start the workflow right away
    # (when the automation's settings allow it).
    trigger_events: tuple[str, ...] = field(default=())


