"""Royalty reports computed from posted/processed data, plus CSV exports
generated by the ``report_generation`` background job."""

import csv
import io
from datetime import date
from decimal import Decimal

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.core.errors import ValidationFailedError
from app.models.catalog import Party, Recording, Work
from app.models.royalty import (
    LedgerEntry,
    Payee,
    RoyaltyAllocation,
    RoyaltyRun,
    RoyaltyStatement,
    StatementLine,
)
from app.services import jobs, storage
from app.services.notifications import notify_user
from app.services.statement_parsing import neutralize_formula

REPORTED_STATUSES = ("processed", "calculated", "posted")

REPORT_TYPES = {
    "revenue_by_source": "Reported revenue by income source",
    "revenue_by_territory": "Reported revenue by territory",
    "revenue_by_work": "Reported revenue by work",
    "revenue_by_recording": "Reported revenue by recording",
    "earnings_by_payee": "Posted payee earnings",
    "payee_balances": "Payee balances (ledger)",
    "statement_reconciliation": "Statement reconciliation",
}


def _statement_filter(stmt, organization_id: str, start: date | None, end: date | None,
                      currency: str | None):
    stmt = stmt.where(RoyaltyStatement.organization_id == organization_id,
                      RoyaltyStatement.status.in_(REPORTED_STATUSES),
                      StatementLine.is_valid.is_(True), StatementLine.match_status != "ignored")
    if start:
        stmt = stmt.where(RoyaltyStatement.period_end >= start)
    if end:
        stmt = stmt.where(RoyaltyStatement.period_end <= end)
    if currency:
        stmt = stmt.where(func.coalesce(StatementLine.currency, RoyaltyStatement.currency) == currency)
    return stmt


def run_report(db: Session, organization_id: str, report_type: str, *, start: date | None = None,
               end: date | None = None, currency: str | None = None, limit: int = 500) -> dict:
    if report_type not in REPORT_TYPES:
        raise ValidationFailedError("Unknown report type", details={"types": list(REPORT_TYPES)})
    line_currency = func.coalesce(StatementLine.currency, RoyaltyStatement.currency)
    amount = func.sum(StatementLine.amount)
    base = select().select_from(StatementLine).join(
        RoyaltyStatement, RoyaltyStatement.id == StatementLine.statement_id)

    if report_type == "revenue_by_source":
        stmt = _statement_filter(base.add_columns(
            RoyaltyStatement.source_category, RoyaltyStatement.source_name, line_currency, amount,
            func.count()), organization_id, start, end, currency).group_by(
            RoyaltyStatement.source_category, RoyaltyStatement.source_name, line_currency)
        columns = ["source_category", "source_name", "currency", "amount", "lines"]
    elif report_type == "revenue_by_territory":
        territory = func.coalesce(StatementLine.territory, "Unknown")
        stmt = _statement_filter(base.add_columns(territory, line_currency, amount, func.count()),
                                 organization_id, start, end, currency).group_by(territory, line_currency)
        columns = ["territory", "currency", "amount", "lines"]
    elif report_type == "revenue_by_work":
        stmt = _statement_filter(
            base.add_columns(Work.id, Work.title, Work.iswc, line_currency, amount, func.count())
            .join(Work, Work.id == StatementLine.work_id), organization_id, start, end, currency,
        ).group_by(Work.id, Work.title, Work.iswc, line_currency)
        columns = ["work_id", "title", "iswc", "currency", "amount", "lines"]
    elif report_type == "revenue_by_recording":
        stmt = _statement_filter(
            base.add_columns(Recording.id, Recording.title, Recording.isrc, line_currency, amount,
                             func.count())
            .join(Recording, Recording.id == StatementLine.recording_id),
            organization_id, start, end, currency,
        ).group_by(Recording.id, Recording.title, Recording.isrc, line_currency)
        columns = ["recording_id", "title", "isrc", "currency", "amount", "lines"]
    elif report_type == "earnings_by_payee":
        stmt = (
            select(Party.id, Party.name, RoyaltyAllocation.currency, func.sum(RoyaltyAllocation.amount),
                   func.count())
            .join(RoyaltyRun, RoyaltyRun.id == RoyaltyAllocation.run_id)
            .join(RoyaltyStatement, RoyaltyStatement.id == RoyaltyRun.statement_id)
            .join(Party, Party.id == RoyaltyAllocation.party_id)
            .where(RoyaltyAllocation.organization_id == organization_id,
                   RoyaltyRun.status == "posted", RoyaltyAllocation.allocation_type == "payable")
            .group_by(Party.id, Party.name, RoyaltyAllocation.currency)
        )
        if start:
            stmt = stmt.where(RoyaltyStatement.period_end >= start)
        if end:
            stmt = stmt.where(RoyaltyStatement.period_end <= end)
        if currency:
            stmt = stmt.where(RoyaltyAllocation.currency == currency)
        columns = ["party_id", "payee", "currency", "amount", "allocations"]
    elif report_type == "payee_balances":
        stmt = (
            select(Payee.id, Payee.display_name, LedgerEntry.currency, func.sum(LedgerEntry.amount),
                   func.count())
            .join(Payee, Payee.id == LedgerEntry.payee_id)
            .where(LedgerEntry.organization_id == organization_id)
            .group_by(Payee.id, Payee.display_name, LedgerEntry.currency)
        )
        if end:
            stmt = stmt.where(LedgerEntry.effective_date <= end)
        if currency:
            stmt = stmt.where(LedgerEntry.currency == currency)
        columns = ["payee_id", "payee", "currency", "balance", "entries"]
    else:  # statement_reconciliation
        stmt = (
            select(RoyaltyStatement.id, RoyaltyStatement.source_name, RoyaltyStatement.period_start,
                   RoyaltyStatement.period_end, RoyaltyStatement.currency, RoyaltyStatement.status,
                   RoyaltyStatement.total_rows, RoyaltyStatement.valid_rows,
                   RoyaltyStatement.matched_rows, RoyaltyStatement.total_amount,
                   RoyaltyStatement.reported_total)
            .where(RoyaltyStatement.organization_id == organization_id)
            .order_by(RoyaltyStatement.period_end.desc())
        )
        if start:
            stmt = stmt.where(RoyaltyStatement.period_end >= start)
        if end:
            stmt = stmt.where(RoyaltyStatement.period_end <= end)
        columns = ["statement_id", "source", "period_start", "period_end", "currency", "status",
                   "rows", "valid_rows", "matched_rows", "total_amount", "reported_total"]

    rows = db.execute(stmt.limit(limit + 1)).all() if report_type == "statement_reconciliation" else \
        db.execute(stmt).all()
    data = [dict(zip(columns, _jsonable_row(row))) for row in rows]
    amount_key = "balance" if report_type == "payee_balances" else "amount"
    total_rows = len(data)
    totals: dict[str, str] = {}
    if report_type != "statement_reconciliation":
        # Totals cover every row, not just the rows shown (audit F-L5).
        sums: dict[str, Decimal] = {}
        for row in data:
            sums[row["currency"]] = sums.get(row["currency"], Decimal("0")) + Decimal(row[amount_key])
        totals = {k: format(v, "f") for k, v in sorted(sums.items())}
        data.sort(key=lambda r: Decimal(r[amount_key]), reverse=True)
    data = data[:limit]
    return {"report_type": report_type, "title": REPORT_TYPES[report_type], "columns": columns,
            "rows": data, "totals_by_currency": totals,
            "row_count": total_rows, "truncated": len(data) < total_rows,
            "filters": {"period_start": start, "period_end": end, "currency": currency}}


def _jsonable_row(row) -> list:
    out = []
    for value in row:
        if isinstance(value, Decimal):
            out.append(format(value, "f"))
        elif isinstance(value, date):
            out.append(value.isoformat())
        else:
            out.append(value)
    return out


def report_csv(report: dict) -> bytes:
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow([report["title"]])
    filters = report["filters"]
    writer.writerow([f"Period end from {filters['period_start'] or '-'} to {filters['period_end'] or '-'}",
                     f"Currency {filters['currency'] or 'all'}"])
    writer.writerow([])
    writer.writerow(report["columns"])
    for row in report["rows"]:
        writer.writerow([neutralize_formula("" if row[c] is None else str(row[c])) for c in report["columns"]])
    if report["totals_by_currency"]:
        writer.writerow([])
        for currency, total in report["totals_by_currency"].items():
            writer.writerow(["Total", currency, total])
    return buffer.getvalue().encode("utf-8-sig")


@jobs.job_handler("report_generation")
def generate_report_job(db: Session, ctx: jobs.JobContext) -> dict:
    payload = ctx.payload
    report_type = payload["report_type"]
    if report_type not in REPORT_TYPES:
        raise jobs.PermanentJobError("Unknown report type")
    start = date.fromisoformat(payload["period_start"]) if payload.get("period_start") else None
    end = date.fromisoformat(payload["period_end"]) if payload.get("period_end") else None
    report = run_report(db, ctx.organization_id, report_type, start=start, end=end,
                        currency=payload.get("currency"), limit=100_000)
    ctx.progress(60)
    filename = f"{report_type}-{date.today().isoformat()}.csv"
    stored = storage.store_generated(db, organization_id=ctx.organization_id, category="export",
                                     filename=filename, data=report_csv(report),
                                     created_by_id=ctx.created_by_id)
    if ctx.created_by_id:
        notify_user(db, user_id=ctx.created_by_id, organization_id=ctx.organization_id,
                    type="report_ready", title=f"Report ready: {REPORT_TYPES[report_type]}",
                    link="/royalties/reports", severity="success")
    return {"file_id": stored.id, "filename": filename, "rows": len(report["rows"])}
