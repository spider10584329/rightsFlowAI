# Shared settings for the RightsFlow AI local n8n scripts. Dot-source it:
#   . "$PSScriptRoot\n8n-common.ps1"
#
# n8n runs natively on Windows (npm install, no Docker). The runtime and its
# data live outside the repository, under %LOCALAPPDATA%\RightsFlowAI\n8n, so
# node_modules and the n8n database never end up in source control.
#
# Instances: the operational instance uses the defaults below. Tests use a
# separate instance (own home, data, secrets, credential, port) by setting
# RIGHTSFLOW_N8N_HOME / RIGHTSFLOW_N8N_PORT / RIGHTSFLOW_N8N_BROKER_PORT, so they
# never touch the operational credential or workflows (audit N8N-01/16).
# The pinned runtime (node_modules) is shared: RIGHTSFLOW_N8N_RUNTIME.

$ErrorActionPreference = 'Stop'

$script:RepoRoot = Split-Path -Parent $PSScriptRoot
$script:N8nVersion = '2.43.5'
$script:N8nHome = if ($env:RIGHTSFLOW_N8N_HOME) { $env:RIGHTSFLOW_N8N_HOME } else { Join-Path $env:LOCALAPPDATA 'RightsFlowAI\n8n' }
$script:N8nRuntime = if ($env:RIGHTSFLOW_N8N_RUNTIME) { $env:RIGHTSFLOW_N8N_RUNTIME } else { Join-Path $env:LOCALAPPDATA 'RightsFlowAI\n8n\runtime' }
$script:N8nData = Join-Path $N8nHome 'data'          # N8N_USER_FOLDER (n8n creates .n8n\ inside)
$script:N8nLogs = Join-Path $N8nHome 'logs'
$script:N8nInbox = Join-Path $N8nHome 'inbox'        # local statement intake folder for Workflow A
$script:N8nSecrets = Join-Path $N8nHome 'secrets'    # encryption key + automation API key (user-only ACL)
$script:N8nEnvFile = Join-Path $N8nSecrets 'n8n.env'
$script:N8nPidFile = Join-Path $N8nHome 'n8n.pid'
$script:N8nPort = if ($env:RIGHTSFLOW_N8N_PORT) { [int]$env:RIGHTSFLOW_N8N_PORT } else { 5678 }
$script:N8nBrokerPort = if ($env:RIGHTSFLOW_N8N_BROKER_PORT) { [int]$env:RIGHTSFLOW_N8N_BROKER_PORT } else { 5679 }
# CLI commands (execute, import, publish) start their own task broker: keep it off the server's.
$script:N8nCliBrokerPort = if ($env:RIGHTSFLOW_N8N_CLI_BROKER_PORT) { [int]$env:RIGHTSFLOW_N8N_CLI_BROKER_PORT } else { $N8nBrokerPort + 10 }
$script:N8nConnectionFile = Join-Path $N8nSecrets 'connection.json'   # which organization this instance serves (no secrets)
$script:N8nInstanceIdFile = Join-Path $N8nData 'rightsflow-instance-id'
$script:BusinessWorkflowIds = @('RfWfRoyaltyImprt', 'RfWfContractExpr', 'RfWfAiReview0001', 'RfWfMonthlyRprt1', 'RfWfHealthCheck1')
$script:N8nBin = Join-Path $N8nRuntime 'node_modules\n8n\bin\n8n'
$script:ApiBaseUrl = if ($env:RIGHTSFLOW_API_URL) { $env:RIGHTSFLOW_API_URL } else { 'http://127.0.0.1:8000' }

function Write-Step([string]$Message) { Write-Host "==> $Message" -ForegroundColor Cyan }
function Write-Ok([string]$Message) { Write-Host "  [ok]   $Message" -ForegroundColor Green }
function Write-Warn2([string]$Message) { Write-Host "  [warn] $Message" -ForegroundColor Yellow }
function Write-Fail([string]$Message) { Write-Host "  [fail] $Message" -ForegroundColor Red }

function Test-PortListening([int]$Port) {
    return [bool](Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue)
}

function Test-HttpOk([string]$Url, [int]$TimeoutSec = 5) {
    try {
        $response = Invoke-WebRequest -Uri $Url -UseBasicParsing -TimeoutSec $TimeoutSec
        return $response.StatusCode -ge 200 -and $response.StatusCode -lt 300
    } catch {
        return $false
    }
}

function Protect-UserOnly([string]$Path) {
    # Restrict a secrets file/folder to the current user (no inherited ACEs).
    $acl = Get-Acl $Path
    $acl.SetAccessRuleProtection($true, $false)
    foreach ($rule in @($acl.Access)) { [void]$acl.RemoveAccessRule($rule) }
    $identity = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name
    $inherit = if ((Get-Item $Path).PSIsContainer) { 'ContainerInherit,ObjectInherit' } else { 'None' }
    $rule = New-Object System.Security.AccessControl.FileSystemAccessRule($identity, 'FullControl', $inherit, 'None', 'Allow')
    $acl.AddAccessRule($rule)
    Set-Acl -Path $Path -AclObject $acl
}

function New-RandomSecret([int]$Bytes = 32) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return ([Convert]::ToBase64String($buffer)).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

function Initialize-N8nFolders {
    foreach ($dir in @($N8nHome, $N8nData, $N8nLogs, $N8nInbox, $N8nSecrets)) {
        if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
    }
    Protect-UserOnly $N8nSecrets
}

function Initialize-N8nEnvFile {
    # Created once. The encryption key protects every credential stored in n8n:
    # losing it makes stored credentials unreadable, so back it up with the data.
    if (Test-Path $N8nEnvFile) { return }
    $key = New-RandomSecret 32
    @(
        '# RightsFlow AI local n8n secrets. Generated by scripts\n8n-common.ps1. Do not commit.',
        "N8N_ENCRYPTION_KEY=$key"
    ) | Set-Content -Path $N8nEnvFile -Encoding ascii
    Protect-UserOnly $N8nEnvFile
}

function Write-Utf8NoBom([string]$Path, [string]$Text) {
    # Windows PowerShell 5.1's "-Encoding utf8" adds a BOM, which n8n's JSON import rejects.
    [System.IO.File]::WriteAllText($Path, $Text, (New-Object System.Text.UTF8Encoding($false)))
}

function Read-EnvFile([string]$Path) {
    $values = @{}
    if (-not (Test-Path $Path)) { return $values }
    foreach ($line in Get-Content $Path) {
        $trimmed = $line.Trim()
        if (-not $trimmed -or $trimmed.StartsWith('#')) { continue }
        $index = $trimmed.IndexOf('=')
        if ($index -gt 0) { $values[$trimmed.Substring(0, $index).Trim()] = $trimmed.Substring($index + 1).Trim() }
    }
    return $values
}

function Get-N8nEnvironment {
    # Process-scoped environment for n8n. Nothing is written to the user or
    # machine environment.
    $secrets = Read-EnvFile $N8nEnvFile
    $settings = Read-EnvFile (Join-Path $RepoRoot 'automation\n8n\n8n.settings.env')
    $envVars = @{}
    foreach ($k in $settings.Keys) { $envVars[$k] = $settings[$k] }
    $envVars['N8N_USER_FOLDER'] = $N8nData
    $envVars['N8N_PORT'] = "$N8nPort"
    $envVars['N8N_RUNNERS_BROKER_PORT'] = "$N8nBrokerPort"
    $envVars['N8N_EDITOR_BASE_URL'] = "http://localhost:$N8nPort"
    $envVars['N8N_LISTEN_ADDRESS'] = '127.0.0.1'
    $envVars['N8N_LOG_FILE_LOCATION'] = (Join-Path $N8nLogs 'n8n.log')
    $envVars['N8N_RESTRICT_FILE_ACCESS_TO'] = $N8nInbox
    $envVars['N8N_ENCRYPTION_KEY'] = $secrets['N8N_ENCRYPTION_KEY']
    return $envVars
}

function Get-N8nInstanceId {
    # Stable id of this n8n installation, kept inside its data folder: a reset or
    # copied data folder gets a new id, which the API detects (instance binding).
    if (-not (Test-Path $N8nData)) { New-Item -ItemType Directory -Path $N8nData -Force | Out-Null }
    if (-not (Test-Path $N8nInstanceIdFile)) {
        Set-Content -Path $N8nInstanceIdFile -Value ('rf-' + [guid]::NewGuid().ToString()) -Encoding ascii -NoNewline
    }
    return (Get-Content $N8nInstanceIdFile -Raw).Trim()
}

function Get-N8nConnection {
    if (-not (Test-Path $N8nConnectionFile)) { return $null }
    return Get-Content $N8nConnectionFile -Raw | ConvertFrom-Json
}

function Invoke-AutomationApi([string]$Token, [string]$Path, [switch]$WithInstance) {
    # Returns @{ Status = <int>; Body = <object|$null>; Error = <string> } and never throws.
    $headers = @{ Authorization = "Bearer $Token" }
    if ($WithInstance) { $headers['X-Automation-Instance'] = Get-N8nInstanceId }
    try {
        $response = Invoke-WebRequest -Uri "$ApiBaseUrl$Path" -Headers $headers -UseBasicParsing -TimeoutSec 15
        return @{ Status = [int]$response.StatusCode; Body = ($response.Content | ConvertFrom-Json); Error = $null }
    } catch {
        $status = 0; $body = $null
        if ($_.Exception.Response) {
            $status = [int]$_.Exception.Response.StatusCode
            try {
                $reader = New-Object System.IO.StreamReader($_.Exception.Response.GetResponseStream())
                $body = $reader.ReadToEnd() | ConvertFrom-Json
            } catch { $body = $null }
        }
        return @{ Status = $status; Body = $body; Error = $_.Exception.Message }
    }
}

function Get-ActiveWorkflowIds {
    $envVars = Get-N8nEnvironment
    $envVars['N8N_RUNNERS_BROKER_PORT'] = "$N8nCliBrokerPort"
    $saved = @{}
    foreach ($k in $envVars.Keys) { $saved[$k] = [Environment]::GetEnvironmentVariable($k, 'Process'); [Environment]::SetEnvironmentVariable($k, $envVars[$k], 'Process') }
    try {
        $lines = & node $N8nBin 'list:workflow' '--active=true' '--onlyId' 2>$null
    } finally {
        foreach ($k in $saved.Keys) { [Environment]::SetEnvironmentVariable($k, $saved[$k], 'Process') }
    }
    return @($lines | Where-Object { $_ -match '^[A-Za-z0-9]{16}$' })
}

function Invoke-N8nCli {
    # Runs the pinned n8n CLI with the RightsFlow environment (process scope only).
    param([Parameter(ValueFromRemainingArguments = $true)][string[]]$Arguments)
    $envVars = Get-N8nEnvironment
    $envVars['N8N_RUNNERS_BROKER_PORT'] = "$N8nCliBrokerPort"
    $saved = @{}
    foreach ($k in $envVars.Keys) {
        $saved[$k] = [Environment]::GetEnvironmentVariable($k, 'Process')
        [Environment]::SetEnvironmentVariable($k, $envVars[$k], 'Process')
    }
    try {
        # Output goes to the console so the function's return value is just the exit code.
        # (No 2>&1: in Windows PowerShell 5.1 that turns stderr lines into errors.)
        & node $N8nBin @Arguments | Out-Host
        return $LASTEXITCODE
    } finally {
        foreach ($k in $saved.Keys) { [Environment]::SetEnvironmentVariable($k, $saved[$k], 'Process') }
    }
}
