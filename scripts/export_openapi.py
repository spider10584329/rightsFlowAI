"""Export the OpenAPI schema and a Markdown endpoint index.

    backend/.venv/Scripts/python.exe scripts/export_openapi.py

Writes docs/openapi.json and docs/API.md (generated — do not edit by hand).
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.main import app  # noqa: E402

schema = app.openapi()
(ROOT / "docs" / "openapi.json").write_text(json.dumps(schema, indent=2), encoding="utf-8")

groups: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
for path, methods in schema["paths"].items():
    for method, op in methods.items():
        tag = (op.get("tags") or ["Other"])[0]
        summary = (op.get("summary") or "").strip()
        groups[tag].append((method.upper(), path, summary))

lines = [
    "# RightsFlow AI — API Reference",
    "",
    "> Generated by `scripts/export_openapi.py` from the live FastAPI app. Do not edit by hand.",
    "> Interactive docs: `http://127.0.0.1:8000/docs` · Schema: [`openapi.json`](openapi.json)",
    "",
    "## Conventions",
    "",
    "- Base path `/api/v1`. Authenticate with `Authorization: Bearer <access_token>` "
    "(browsers use the Next.js BFF with httpOnly cookies instead).",
    "- Tenant routes: `/organizations/{organization_id}/...`; non-members receive **404**, "
    "insufficient role **403**.",
    "- Errors: `{\"error\": {\"code\", \"message\", \"details\"}, \"detail\", \"request_id\"}`.",
    "- Lists: `?page=&page_size=&sort=&order=asc|desc` → `{items, total, page, page_size, pages}`.",
    "- Money and percentages are JSON strings (exact decimals).",
    "- Plan limits: **402** `plan_limit_exceeded`; AI not configured: **503** `ai_not_configured`.",
    "",
    f"Total operations: **{sum(len(v) for v in groups.values())}**",
    "",
]
for tag in sorted(groups):
    lines += [f"## {tag}", "", "| Method | Path | Summary |", "|---|---|---|"]
    for method, path, summary in sorted(groups[tag], key=lambda r: (r[1], r[0])):
        lines.append(f"| `{method}` | `{path}` | {summary} |")
    lines.append("")
(ROOT / "docs" / "API.md").write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {sum(len(v) for v in groups.values())} operations across {len(groups)} tags")
